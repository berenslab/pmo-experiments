"""Aggregate evaluation scores from multiple models and datasets into CSV files."""

import glob
import json
import logging
import os
from concurrent.futures import ThreadPoolExecutor, as_completed
from copy import deepcopy
from typing import Any

import pandas as pd
from tqdm.auto import tqdm

from pmo_experiments.evaluation import ScoresResult

logger = logging.getLogger(__name__)


def discover_eval_files(evaluation_folder_path: str) -> dict[str, list[str]]:
    """
    Discover all evaluation files in the given folder.

    Args:
        evaluation_folder_path (str): Folder containing evaluation results.

    Returns:
        dict[str, list[str]]: Dictionary mapping evaluation settings to lists of file
            paths.

    """
    evaluation_setting_files = {
        "knn": glob.glob(
            os.path.join(evaluation_folder_path, "**", "*_knn_report.json"),
            recursive=True,
        ),
        "knn_distance_weighted": glob.glob(
            os.path.join(
                evaluation_folder_path, "**", "*_knn_distance_weighted_report.json"
            ),
            recursive=True,
        ),
        "zero_shot": glob.glob(
            os.path.join(evaluation_folder_path, "**", "*_zero_shot_report.json"),
            recursive=True,
        ),
        "linear_probing": glob.glob(
            os.path.join(
                evaluation_folder_path, "**", "linear_probing_C*", "*_report.json"
            ),
            recursive=True,
        ),
    }

    # Split linear probing in base and balanced
    evaluation_setting_files["linear_probing_balanced"] = [
        f
        for f in evaluation_setting_files["linear_probing"]
        if os.path.basename(os.path.dirname(f)).endswith("_balanced")
    ]
    evaluation_setting_files["linear_probing"] = [
        f
        for f in evaluation_setting_files["linear_probing"]
        if not os.path.basename(os.path.dirname(f)).endswith("_balanced")
    ]

    return evaluation_setting_files


def load_eval_settings(
    norm_file_name: str, run_prefix: str = "pmo-experiment"
) -> dict[str, str | int | None]:
    """
    Load the model and eval settings from the normalized file name.

    Args:
        norm_file_name (str): File name generated by evaluation script.
        run_prefix (str): Prefix for the run name. Usually constructed from the wandb
            project name and metadata. Defaults to "pmo-experiment".

    Returns:
        dict[str, str | int | None]: Evaluation and model settings extracted from the
            file name.

    """
    model_name = norm_file_name.split(os.path.sep, maxsplit=1)[0]
    eval_dataset_name = norm_file_name.split(model_name + os.path.sep)[1].split(
        os.path.sep, maxsplit=1
    )[0]

    if model_name.startswith(run_prefix):
        model_type = "finetuned"
        epoch = int(model_name.split("_epoch")[1])
        batch_size = model_name.split("_bs")[-1].split("_")[0]
        seed = model_name.split(f"_bs{batch_size}_s")[-1].split("_")[0]

        arch_weight_dataset = model_name.removeprefix(f"{run_prefix}_").split(
            f"_bs{batch_size}_s{seed}"
        )[0]
        model_architecture = None

        if arch_weight_dataset.startswith("RN50x4"):
            model_architecture = "RN50x4"
        elif arch_weight_dataset.startswith("RN50"):
            model_architecture = "RN50"
        elif arch_weight_dataset.lower().replace("_", "-").startswith("vit-b-16"):
            model_architecture = "ViT-B/16"
        elif arch_weight_dataset.lower().replace("_", "-").startswith("vit-l-14"):
            model_architecture = "ViT-L/14"
        elif arch_weight_dataset.lower().replace("_", "-").startswith("vit-b-32"):
            model_architecture = "ViT-B/32"

        pretraining_weights = None
        if "openai" in arch_weight_dataset:
            pretraining_weights = "openai"
        elif "biomed_clip" in arch_weight_dataset:
            pretraining_weights = "biomed_clip"
        elif "scratch" in arch_weight_dataset:
            pretraining_weights = "scratch"

        training_dataset = arch_weight_dataset.split(f"{pretraining_weights}_")[-1]
    else:
        model_type = "baseline"
        epoch = None
        batch_size = None
        seed = None
        model_architecture = "ViT-B/16"
        pretraining_weights = "openai" if "openai" in model_name else "biomed_clip"
        training_dataset = "openai" if "openai" in model_name else "pmc15m"

    return {
        "eval_dataset_name": eval_dataset_name,
        "model_name": model_name,
        "model_type": model_type,
        "epoch": epoch,
        "batch_size": batch_size,
        "seed": seed,
        "model_architecture": model_architecture,
        "pretraining_weights": pretraining_weights,
        "training_dataset": training_dataset,
    }


def load_column_scores(
    column_score_dict: ScoresResult,
) -> dict[str, float | None | bool]:
    """
    Load scores into target format.

    Args:
        column_score_dict (ScoresResult): Evaluation score.

    Raises:
        KeyError: Missing keys.

    Returns:
        dict[str, float | None | bool]: Dictionary containing the scores for the target
            value. Has the following keys:
            - "accuracy"
            - "balanced_accuracy"
            - "auroc"
            - "aupr"
            - "auc"
            - "auprc"
            - "zero_support" (bool indicating if any target value had zero support)

    """
    loaded_categories = {}

    found_zero_support = False

    if "classification_report" not in column_score_dict:
        raise KeyError("classification_report not found in column_score_dict")

    rec_balanced_accuracy = 0.0
    for score_key, val in column_score_dict["classification_report"].items():
        if score_key in [
            "accuracy",
            "macro_avg",
            "weighted_avg",
            "macro avg",
            "weighted avg",
        ]:
            continue

        category_name = val["text"]

        loaded_categories[category_name] = {
            "support": val["support"],
            "name": category_name,
        }

        if val["support"] == 0:
            found_zero_support = True
        else:
            rec_balanced_accuracy += val["recall"]

    if found_zero_support:
        accuracy = None
        balanced_accuracy = None
        auroc = None
        aupr = None
        auc = None
        auprc = None
    else:
        accuracy = column_score_dict["classification_report"]["accuracy"]
        balanced_accuracy = column_score_dict["classification_report"]["macro avg"][
            "recall"
        ]
        auroc = column_score_dict.get("auroc", None)
        aupr = column_score_dict.get("aupr", None)
        auc = column_score_dict.get("auc", None)
        auprc = column_score_dict.get("auprc", None)

    return {
        "accuracy": accuracy,
        "balanced_accuracy": balanced_accuracy,
        "auroc": auroc,
        "aupr": aupr,
        "auc": auc,
        "auprc": auprc,
        "zero_support": found_zero_support,
    }


def load_scores_knn_zero_shot(file_path: str) -> list[dict[str, float | None | bool]]:
    """
    Load scores from a file saved by the zero-shot, knn and knn-dw evaluations.

    Args:
        file_path (str): Path to the file to load

    Returns:
        list[dict[str, float | None | bool]]: List of dictionaries containing the
            scores for each target value in the file and the "column_name" key
            indicating the target value.

    """
    with open(file_path) as f:
        knn_report = json.load(f)

    full_scores = []

    for target_value, scores in knn_report.items():
        if target_value == "k" and isinstance(scores, int):
            continue

        try:
            column_scores = load_column_scores(scores)
        except KeyError as e:
            logger.error(
                f"Error loading column scores for {file_path} and "
                f"target {target_value}: {e}"
            )
            full_scores.append(
                {
                    "column_name": target_value,
                    "accuracy": None,
                    "balanced_accuracy": None,
                    "auroc": None,
                    "aupr": None,
                    "auc": None,
                    "auprc": None,
                    "zero_support": None,
                }
            )
            continue

        full_scores.append(
            {
                "column_name": target_value,
                **column_scores,
            }
        )
    return full_scores


def load_scores_linear_probing(
    file_path: str,
) -> list[dict[str, float | None | bool | str]]:
    """
    Load scores from a file saved by the lin. probing and balanced lin. probing evals.

    Args:
        file_path (str): Path to the file to load

    Returns:
        list[dict[str, float | None | bool | str]]: List of dictionaries containing the
            scores for each target value in the file. The "column_name" key
            indicates the target value, the "C_value" key indicates the C value used
            for the linear probing and "is_balanced" is True for balanced linear
            probing and false else.

    """
    with open(file_path) as f:
        lp_report = json.load(f)

    column_name = os.path.basename(file_path).split("_report.json")[0]

    C_value = lp_report["model_parameters"]["C"]
    is_balanced = lp_report["model_parameters"]["balanced"]

    try:
        column_scores = load_column_scores(lp_report)
    except KeyError as e:
        logger.error(f"Error loading column scores for {file_path}: {e}")
        column_scores = {
            "accuracy": None,
            "balanced_accuracy": None,
            "auroc": None,
            "aupr": None,
            "auc": None,
            "auprc": None,
            "zero_support": None,
        }

    return [
        {
            "column_name": column_name,
            "C_value": C_value,
            "is_balanced": is_balanced,
            **column_scores,
        }
    ]


def load_scores(
    model_settings_dict: dict[str, Any],
) -> dict[str, dict[str, list[dict[str, float | None | bool]]]]:
    """
    Load evaluation scores for the given model settings.

    Args:
        model_settings_dict (dict[str, Any]): Dictionary with evaluation and model
            settings.

    Raises:
        ValueError: For an unknown evaluation setting.

    Returns:
        dict[str, dict[str, list[dict[str, float | None | bool]]]]: Dictionary mapping
            dataset names to evaluation settings to lists of score dictionaries.

    """
    loaded_score_dict = {}

    for dataset_name, eval_settings in model_settings_dict["eval_files"].items():
        for eval_setting, files in eval_settings.items():
            for file in files:
                if eval_setting in ["knn", "zero_shot", "knn_distance_weighted"]:
                    scores = load_scores_knn_zero_shot(file)
                elif eval_setting in ["linear_probing", "linear_probing_balanced"]:
                    scores = load_scores_linear_probing(file)
                else:
                    raise ValueError(f"Unknown evaluation setting: {eval_setting}")

                if dataset_name not in loaded_score_dict:
                    loaded_score_dict[dataset_name] = {}
                if eval_setting not in loaded_score_dict[dataset_name]:
                    loaded_score_dict[dataset_name][eval_setting] = []
                loaded_score_dict[dataset_name][eval_setting].extend(scores)

    return loaded_score_dict


def convert_to_flat_df(all_settings_dict: dict[str, dict[str, Any]]) -> pd.DataFrame:
    """
    Convert the nested dictionary of all settings and scores into a flat pandas df.

    Args:
        all_settings_dict (dict[str, dict[str, Any]]): Nested dictionary containing
            model settings and scores.

    Returns:
        pd.DataFrame: DataFrame containing all model settings and scores in a flat
            format, with one row per score entry.

    """
    record_list = []

    for model_name, model_settings in all_settings_dict.items():
        base_record = {
            "model_name": model_name,
            "model_type": model_settings["model_type"],
            "epoch": model_settings["epoch"],
            "batch_size": int(model_settings["batch_size"])
            if model_settings["batch_size"] is not None
            else None,
            "seed": int(model_settings["seed"])
            if model_settings["seed"] is not None
            else None,
            "model_architecture": model_settings["model_architecture"],
            "pretraining_weights": model_settings["pretraining_weights"],
            "training_dataset": model_settings["training_dataset"],
        }

        for dataset_name, dataset_scores in model_settings["scores"].items():
            for eval_setting, scores in dataset_scores.items():
                for score_dict in scores:
                    record = deepcopy(base_record)
                    record["eval_dataset_name"] = dataset_name
                    record["eval_setting"] = eval_setting
                    record.update(score_dict)
                    record_list.append(record)

    return pd.DataFrame(record_list)


def load_evaluation_scores_as_df_parallel(
    evaluation_folder_path: str,
    max_workers: int = 8,
    run_prefix: str = "pmo-experiment",
) -> pd.DataFrame:
    """
    Load the test or val evaluation scored from the folder into a df.

    Args:
        evaluation_folder_path (str): Folder to parse. Generated by evaluation script.
        max_workers (int, optional): Number of threads that work in parallel. Defaults
            to 8.
        run_prefix (str, optional): Prefix for the run name. Usually constructed from
                    the wandb project name and metadata. Defaults to "pmo-experiment".

    Returns:
        pd.DataFrame: DataFrame containing all model settings and scores in a flat
            format, with one row per score entry.

    """
    evaluation_setting_files = discover_eval_files(evaluation_folder_path)

    settings_map = {}

    # First pass is cheap (path parsing + dict building) -- kept sequential.
    for eval_setting, files in evaluation_setting_files.items():
        for file in files:
            norm_path = file.removeprefix(evaluation_folder_path + os.path.sep)

            model_settings = load_eval_settings(norm_path, run_prefix=run_prefix)
            model_name = model_settings["model_name"]
            eval_dataset_name = model_settings.pop("eval_dataset_name")

            if model_name not in settings_map:
                settings_map[model_name] = {**model_settings, "eval_files": {}}
            if eval_dataset_name not in settings_map[model_name]["eval_files"]:
                settings_map[model_name]["eval_files"][eval_dataset_name] = {}
            if (
                eval_setting
                not in settings_map[model_name]["eval_files"][eval_dataset_name]
            ):
                settings_map[model_name]["eval_files"][eval_dataset_name][
                    eval_setting
                ] = []

            settings_map[model_name]["eval_files"][eval_dataset_name][
                eval_setting
            ].append(file)

    # Second pass is IO-bound (disk reads + JSON parsing per model) -- parallelized.
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_model = {
            executor.submit(load_scores, model_settings): model_name
            for model_name, model_settings in settings_map.items()
        }
        for future in tqdm(as_completed(future_to_model), total=len(future_to_model)):
            model_name = future_to_model[future]
            settings_map[model_name]["scores"] = future.result()

    df = convert_to_flat_df(settings_map)

    return df


def create_aggregated_csv(
    evaluation_folder_path: str,
    number_of_threads: int = 6,
    aggregation_output_path: str | None = None,
    metric_list: list[str] | None = None,
    run_prefix: str = "pmo-experiment",
):
    """
    Aggregate the evaluation results into csv files.

    Args:
        evaluation_folder_path (str): Output folder of the evaluation script.
        number_of_threads (int, optional): Number of threads used for processing.
            Defaults to 6.
        aggregation_output_path (str | None, optional): Path to save the aggregated csv
            files to. If None creates folder 'aggregated_scores' in the
            evaluation_folder_path. Defaults to None.
        metric_list (list[str] | None, optional): List of metrics that can be
            aggregated. If None defaults to 'balanced_accuracy', 'auroc' and 'auprc'.
            Defaults to None. Available metrics are:
            - 'accuracy'
            - 'balanced_accuracy'
            - 'auroc'
            - 'aupr'
            - 'auc'
            - 'auprc'
        run_prefix (str, optional): Prefix for the run name. Usually constructed from
            the wandb project name and metadata. Defaults to "pmo-experiment".

    Raises:
        FileNotFoundError: If the evaluation folder path does not exist.

    """
    if not os.path.exists(evaluation_folder_path):
        raise FileNotFoundError(
            f"Evaluation folder path '{evaluation_folder_path}' does not exist."
        )

    test_time_eval_folder = os.path.join(evaluation_folder_path, "test")
    val_time_eval_folder = os.path.join(evaluation_folder_path, "val")

    if not os.path.exists(test_time_eval_folder):
        raise FileNotFoundError(
            f"Test folder path '{test_time_eval_folder}' does not exist."
            "\nRun the evaluation script with --eval-dataset-split test to generate "
            "test time evaluation results."
        )

    if not os.path.exists(val_time_eval_folder):
        raise FileNotFoundError(
            f"Validation folder path '{val_time_eval_folder}' does not exist."
            "\nRun the evaluation script with --eval-dataset-split val to generate "
            "validation time evaluation results."
        )

    if aggregation_output_path is None:
        aggregation_output_path = os.path.join(
            evaluation_folder_path, "aggregated_scores"
        )

    if metric_list is None:
        metric_list = [
            "balanced_accuracy",
            "auroc",
            "auprc",
        ]
    else:
        available_metrics = [
            "accuracy",
            "balanced_accuracy",
            "auroc",
            "aupr",
            "auc",
            "auprc",
        ]
        for metric in metric_list:
            if metric not in available_metrics:
                raise ValueError(
                    f"Metric '{metric}' is not available. "
                    "Available metrics are: {available_metrics}"
                )

    os.makedirs(aggregation_output_path, exist_ok=True)

    # Collect evaluation results
    test_time_score_df = load_evaluation_scores_as_df_parallel(
        test_time_eval_folder, max_workers=number_of_threads, run_prefix=run_prefix
    )
    val_time_score_df = load_evaluation_scores_as_df_parallel(
        val_time_eval_folder, max_workers=number_of_threads, run_prefix=run_prefix
    )

    # Find targets with 0 support
    zero_support_fraction_test = (
        test_time_score_df.groupby(["eval_dataset_name", "column_name"])[
            "zero_support"
        ].sum()
        / test_time_score_df.groupby(["eval_dataset_name", "column_name"])[
            "zero_support"
        ].count()
    ).reset_index()

    zero_support_fraction_test[zero_support_fraction_test["zero_support"] > 0.0]

    zero_support_fraction_val = (
        val_time_score_df.groupby(["eval_dataset_name", "column_name"])[
            "zero_support"
        ].sum()
        / val_time_score_df.groupby(["eval_dataset_name", "column_name"])[
            "zero_support"
        ].count()
    ).reset_index()

    zero_support_fraction_val[zero_support_fraction_val["zero_support"] > 0.0]

    # Get the linear probing best C values
    best_lp_C_val = (
        val_time_score_df[(val_time_score_df["eval_setting"] == "linear_probing")][
            ["model_name", "eval_dataset_name", "C_value", "balanced_accuracy"]
        ]
        .groupby(["model_name", "eval_dataset_name", "C_value"])
        .mean()
        .reset_index()
        .sort_values("C_value")
        .groupby(["model_name", "eval_dataset_name"])
        .apply(lambda x: x.loc[x["balanced_accuracy"].idxmax()], include_groups=False)[  # pyright: ignore[reportCallIssue,reportAttributeAccessIssue,reportIndexIssue]
            "C_value"
        ]
    )

    best_balanced_lp_C_val = (
        val_time_score_df[
            (val_time_score_df["eval_setting"] == "linear_probing_balanced")
        ][["model_name", "eval_dataset_name", "C_value", "balanced_accuracy"]]
        .groupby(["model_name", "eval_dataset_name", "C_value"])
        .mean()
        .reset_index()
        .sort_values("C_value")
        .groupby(["model_name", "eval_dataset_name"])
        .apply(lambda x: x.loc[x["balanced_accuracy"].idxmax()], include_groups=False)[  # pyright: ignore[reportCallIssue,reportAttributeAccessIssue,reportIndexIssue]
            "C_value"
        ]
    )

    # Remove linear probing and balanced linear probing for other C values
    def filter_lp_C_values(row):
        if row["eval_dataset_name"] in ["idrid_disease_grading", "idrid_segmentation"]:
            # Datasets without validation splits
            return False
        if row["eval_setting"] == "linear_probing":
            if (row["model_name"], row["eval_dataset_name"]) not in best_lp_C_val.index:
                return False
            best_C = best_lp_C_val.loc[(row["model_name"], row["eval_dataset_name"])]
            return row["C_value"] == best_C
        elif row["eval_setting"] == "linear_probing_balanced":
            if (
                row["model_name"],
                row["eval_dataset_name"],
            ) not in best_balanced_lp_C_val.index:
                return False
            best_C = best_balanced_lp_C_val.loc[
                (row["model_name"], row["eval_dataset_name"])
            ]
            return row["C_value"] == best_C
        else:
            return True

    filtered_test_time_scores = test_time_score_df[
        test_time_score_df.apply(filter_lp_C_values, axis=1)
    ].copy()
    filtered_val_time_scores = val_time_score_df[
        val_time_score_df.apply(filter_lp_C_values, axis=1)
    ].copy()

    # Save full filtered scores to CSV for further analysis
    filtered_test_time_scores.to_csv(
        os.path.join(aggregation_output_path, "filtered_test_time_scores.csv"),
        index=False,
    )
    filtered_val_time_scores.to_csv(
        os.path.join(aggregation_output_path, "filtered_val_time_scores.csv"),
        index=False,
    )

    # Average across seeds and save aggregated scores to CSV files
    setting_column_names = [
        "model_name",
        "model_type",
        "epoch",
        "batch_size",
        "seed",
        "model_architecture",
        "pretraining_weights",
        "training_dataset",
        "eval_setting",
    ]

    test_time_score_dict = {}
    val_time_score_dict = {}

    filtered_test_time_scores["proxy_column"] = (
        filtered_test_time_scores["eval_dataset_name"]
        + "::"
        + filtered_test_time_scores["column_name"]
    )
    filtered_val_time_scores["proxy_column"] = (
        filtered_val_time_scores["eval_dataset_name"]
        + "::"
        + filtered_val_time_scores["column_name"]
    )

    test_time_model_data = (
        filtered_test_time_scores.drop(
            columns=[
                "eval_setting",
                "eval_dataset_name",
                "column_name",
                "accuracy",
                "balanced_accuracy",
                "auroc",
                "aupr",
                "auc",
                "auprc",
                "zero_support",
                "proxy_column",
                "C_value",
                "is_balanced",
            ]
        )
        .set_index("model_name")
        .drop_duplicates()
    )

    for metric in metric_list:
        test_time_score_dict[metric] = (
            filtered_test_time_scores[(~filtered_test_time_scores["zero_support"])]
            .pivot(
                index=["model_name", "eval_setting"],
                columns="proxy_column",
                values=metric,
            )
            .join(other=test_time_model_data, on="model_name", how="left")
            .reset_index()
            .copy()
        )

        test_time_score_dict[metric] = test_time_score_dict[metric][
            setting_column_names
            + [
                col
                for col in test_time_score_dict[metric].columns
                if col not in setting_column_names
            ]
        ]

        val_time_score_dict[metric] = (
            filtered_val_time_scores[(~filtered_val_time_scores["zero_support"])]
            .pivot(
                index=["model_name", "eval_setting"],
                columns="proxy_column",
                values=metric,
            )
            .join(other=test_time_model_data, on="model_name", how="left")
            .reset_index()
            .copy()
        )
        val_time_score_dict[metric] = val_time_score_dict[metric][
            setting_column_names
            + [
                col
                for col in val_time_score_dict[metric].columns
                if col not in setting_column_names
            ]
        ]

    setting_columns_wo_seed = [
        col for col in setting_column_names if col != "seed" and col != "model_name"
    ]

    # Save aggregated scores to CSV files
    for metric, metric_df in test_time_score_dict.items():
        (
            metric_df.drop(columns=["seed", "model_name"])
            .groupby(setting_columns_wo_seed, dropna=False)
            .mean()
            .reset_index()
            .drop(columns=["model_type", "epoch"])
        ).to_csv(
            os.path.join(aggregation_output_path, f"final_test_scores_{metric}.csv"),
            index=False,
        )
